export const formatMoney = (value: number) => {
  const absolute = Math.abs(value);
  const formatted = absolute >= 1000000 ? `$${(absolute / 1000000).toFixed(1)}M` : `$${(absolute / 1000).toFixed(0)}K`;
  return value < 0 ? `(${formatted})` : formatted;
};

